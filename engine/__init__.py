def show_ending(karma):
    print("\n--- AKHIR DUNIA ---\n")
    if karma <= -3:
        print("Dosa meracuni segalanya. Dunia menjadi tempat tanpa kasih, penuh kecurigaan.")
    elif -3 < karma <= 2:
        print("Dunia bertahan, tapi penuh luka. Tak ada yang benar-benar bersih.")
    elif karma > 2:
        print("Dunia tetap terang. Harapan berakar, dan jiwa-jiwa baru terlahir dalam damai.")
